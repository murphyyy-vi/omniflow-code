import type { Answers, DimensionKey } from '../questionnaire';

export type Campus = 'pukou' | 'mochou';
export type Gender = 'male' | 'female';
export type Stage = 'questionnaire' | 'profile';

export interface UserDto {
  id: string;
  studentId: string;
  name: string;
  gender: Gender;
  major: string;
  campus: Campus;
  role: 'student' | 'counselor' | 'admin';
}

export type RadarData = Record<DimensionKey, number>;

export interface ProfileVersion {
  radar: RadarData;
  tags: string[];
  summary: string;
}

export interface AnomalyFlag {
  type: 'lie_detector' | 'dummy' | 'too_fast';
  message: string;
}

export interface RegisterRequest {
  studentId: string;
  name: string;
  gender: Gender;
  major: string;
  campus: Campus;
}

export interface LoginRequest {
  studentId: string;
  name: string;
}

export interface AuthResponse {
  token: string;
  user: UserDto;
  stage: Stage;
}

export interface MeResponse {
  user: UserDto;
  stage: Stage;
}

export interface DraftResponse {
  answers: Answers;
  submitted: boolean;
}

export interface SaveDraftRequest {
  answers: Answers;
}

export interface SubmitQuestionnaireRequest {
  answers: Answers;
}

export interface ProfileDto {
  aiVersion: ProfileVersion;
  /** 'ai' when generated by the LLM, 'rule' when the rule-based template was used. */
  source: 'ai' | 'rule';
  studentVersion: ProfileVersion;
  edited: boolean;
  priorityDimensions: DimensionKey[];
  submittedAt: string;
  updatedAt: string;
}

export interface SaveProfileRequest {
  radar: RadarData;
  tags: string[];
  priorityDimensions: DimensionKey[];
}
